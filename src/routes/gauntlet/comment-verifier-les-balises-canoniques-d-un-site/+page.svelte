<h1>Vérification des balises canoniques</h1>
<p>Cette page fournit des instructions sur la manière de vérifier les balises canoniques d'un site web. Les balises canoniques sont essentielles pour indiquer aux moteurs de recherche quelle version d'une page doit être indexée, surtout en cas de contenu dupliqué.</p>
<p>Pour vérifier les balises canoniques, commencez par inspecter le code source de la page. Recherchez la balise <code>&lt;link rel="canonical" href="..." /&gt;</code> et assurez-vous qu'elle pointe vers l'URL correcte. Utilisez également des outils comme Google Search Console pour détecter d'éventuelles erreurs liées aux balises canoniques.</p>
<p>Enfin, il est recommandé de tester les pages avec des outils d'audit SEO pour s'assurer que les balises canoniques sont correctement mises en place et qu'elles ne causent pas de problèmes d'indexation.</p>
